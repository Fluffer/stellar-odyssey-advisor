// i18n.js — the GUI's string catalogue and lookup runtime.
//
// The advisor's HTML is built by string concatenation in app.js, so there is
// no template layer to hang translations off. Instead every user-facing
// literal moved into the catalogue below and the render code calls t(key).
//
// House pattern (same as pet-math.js / unit-math.js): loads in the browser as
// window.I18n and in Node as a CommonJS module, so tests can check that the
// two catalogues cover the same keys without a DOM.
//
// Conventions
//   keys      "<section>.<snake_case>", e.g. "units.emu_title"
//   vars      "{name}" placeholders, filled from the second argument
//   escaping  t() returns RAW text. Catalogue strings may contain entities
//             (&mdash;) and markup (<b>) on purpose, so callers keep using
//             esc() on game data exactly as before.
//   numbers   fmtC/fmtN keep en-US grouping and K/M/B/T suffixes in both
//             languages: they are read against the game's own numbers, which
//             the advisor never re-localises.

