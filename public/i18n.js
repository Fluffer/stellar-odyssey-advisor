const CATALOG = { en: EN, zh: ZH };

// The stored preference wins; otherwise a Chinese browser opens in Chinese.
function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && CATALOG[saved]) return saved;
  } catch (e) {}
  try {
    if (typeof navigator !== "undefined" && /^zh/i.test(navigator.language || "")) return "zh";
  } catch (e) {}
  return "en";
}

const I18n = {
  LANGS,
  LANG_NAMES,
  CATALOG,
  lang: "en",
};

// Missing translations fall back to English rather than to a bare key: a
// half-translated catalogue still produces a usable page.
function t(key, vars) {
  const table = CATALOG[I18n.lang] || EN;
  let s = table[key];
  if (s === undefined) s = EN[key];
  if (s === undefined) return key;
  if (!vars) return s;
  return String(s).replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m);
}
I18n.t = t;

// Keys the given language does not translate (English falls through for them).
// Used by the test suite to keep the two catalogues in step.
I18n.missing = function (lang) {
  const table = CATALOG[lang] || {};
  return Object.keys(EN).filter(k => table[k] === undefined);
};

// Keys a language defines that English does not — i.e. stale entries left
// behind when an English string was renamed or removed.
I18n.extra = function (lang) {
  const table = CATALOG[lang] || {};
  return Object.keys(table).filter(k => EN[k] === undefined);
};

// ---- static markup ----------------------------------------------------
// index.html carries data-i18n / data-i18n-html / data-i18n-title attributes;
// this fills them in for the current language. -html is for strings that
// contain entities or markup on purpose (&mdash;, &amp;).
I18n.applyStatic = function (root) {
  const doc = root || (typeof document !== "undefined" ? document : null);
  if (!doc || !doc.querySelectorAll) return;
  doc.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  doc.querySelectorAll("[data-i18n-html]").forEach(el => {
    // Tab buttons carry a .tabcount badge that render() owns; replacing the
    // whole innerHTML would drop it, so keep it and swap only the label.
    const badge = el.querySelector && el.querySelector(".tabcount");
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
    if (badge) el.appendChild(badge);
  });
  doc.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  if (doc.title !== undefined && doc.querySelector) doc.title = t("app.title");
};

I18n.setLang = function (lang) {
  if (!CATALOG[lang]) return I18n.lang;
  I18n.lang = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  if (typeof document !== "undefined") {
    if (document.documentElement) document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    I18n.applyStatic();
    const sel = document.getElementById("lang");
    if (sel && sel.value !== lang) sel.value = lang;
  }
  // Re-render whatever is on screen. The history tab loads its own data.
  if (typeof window !== "undefined") {
    if (window.activeTab === "history" && typeof window.loadHistory === "function") window.loadHistory();
    else if (window.lastData && typeof window.render === "function") window.render(window.lastData);
  }
  return I18n.lang;
};

I18n.lang = detectLang();

if (typeof module !== "undefined" && module.exports) module.exports = I18n;
if (typeof window !== "undefined") {
  window.I18n = I18n;
  window.t = t;
  // The catalogue must be in place before app.js builds any HTML.
  if (typeof document !== "undefined" && document.documentElement) {
    document.documentElement.lang = I18n.lang === "zh" ? "zh-CN" : "en";
  }
}
